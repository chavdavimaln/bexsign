/**
 * Writes the structure of the development database to server/database/schema.sql (and the built-in roles to
 * server/database/seed.sql). Run it after the application has added tables or columns, so the migration script
 * (scripts/migrate.js) can bring every other database to the same structure.
 *
 *   npm run db:snapshot            (in server/)
 *
 * Only structure is written: no documents, users or any other data leave the database.
 */
const fs = require('fs');
const path = require('path');
require('dotenv').config({ path: path.join(__dirname, '..', '.env') });
const mysql = require('mysql2/promise');

const OUT_DIR = path.join(__dirname, '..', 'database');
const DB_NAME = process.env.DB_NAME || 'db_bex_sign';

const sqlValue = (value) => {
  if (value === null || value === undefined) return 'NULL';
  if (typeof value === 'number') return String(value);
  if (value instanceof Date) return `'${value.toISOString().slice(0, 19).replace('T', ' ')}'`;
  return `'${String(typeof value === 'object' ? JSON.stringify(value) : value).replace(/\\/g, '\\\\').replace(/'/g, "''")}'`;
};

(async () => {
  const connection = await mysql.createConnection({
    host: process.env.DB_HOST || 'localhost',
    port: Number(process.env.DB_PORT) || 3306,
    user: process.env.DB_USER || 'root',
    password: process.env.DB_PASSWORD || '',
    database: DB_NAME
  });
  try {
    // The application creates and extends several tables itself: make sure they are all there first
    try {
      await require('../utils/platformSchema').ensurePlatformSchema();
      await require('../utils/requestHelpers').ensureRequestSchema();
      await require('../utils/cloudStorage').ensureCloudSchema();
    } catch (err) {
      console.warn('[snapshot] The application schema helpers did not all run:', err.message);
    }

    const [tables] = await connection.query(
      "SELECT TABLE_NAME AS name FROM information_schema.TABLES WHERE TABLE_SCHEMA = ? AND TABLE_TYPE = 'BASE TABLE' AND TABLE_NAME <> 'schema_migrations' ORDER BY TABLE_NAME",
      [DB_NAME]
    );
    const [[{ version }]] = await connection.query('SELECT VERSION() AS version');
    const blocks = [];
    for (const { name } of tables) {
      const [[row]] = await connection.query(`SHOW CREATE TABLE \`${name}\``);
      const create = String(row['Create Table'])
        .replace(/^CREATE TABLE /, 'CREATE TABLE IF NOT EXISTS ')
        .replace(/ AUTO_INCREMENT=\d+/, '');
      blocks.push(`-- ----------------------------------------------------------------\n-- ${name}\n-- ----------------------------------------------------------------\n${create};`);
    }

    const header = [
      '-- BexSign database structure.',
      '-- GENERATED by "npm run db:snapshot" (server/scripts/snapshot-schema.js). Do not edit by hand:',
      '-- change the database through the application, then run the snapshot again.',
      '--',
      '-- Apply it with "npm run db:migrate" (server/scripts/migrate.js), which creates missing tables and adds',
      '-- missing columns and indexes without touching existing data. See doc/30-database-migration.md.',
      `-- Tables: ${tables.length}. Source server: ${version}.`,
      '',
      'SET NAMES utf8mb4;',
      'SET FOREIGN_KEY_CHECKS = 0;',
      ''
    ].join('\n');
    fs.mkdirSync(OUT_DIR, { recursive: true });
    fs.writeFileSync(path.join(OUT_DIR, 'schema.sql'), `${header}\n${blocks.join('\n\n')}\n\nSET FOREIGN_KEY_CHECKS = 1;\n`);

    // Reference data the application does not create by itself: the three built-in roles
    const [roles] = await connection.query("SELECT * FROM roles WHERE role_key IN ('manager', 'leader', 'team_member') ORDER BY id");
    const seed = [
      '-- BexSign reference data: the built-in roles.',
      '-- GENERATED by "npm run db:snapshot". Applied by "npm run db:migrate"; existing rows are never changed.',
      '',
      ...roles.map((role) => {
        const columns = Object.keys(role).filter((c) => !['created_at', 'updated_at'].includes(c));
        return `INSERT IGNORE INTO \`roles\` (${columns.map((c) => `\`${c}\``).join(', ')}) VALUES (${columns.map((c) => sqlValue(role[c])).join(', ')});`;
      }),
      ''
    ].join('\n');
    fs.writeFileSync(path.join(OUT_DIR, 'seed.sql'), seed);

    console.log(`[snapshot] ${tables.length} tables written to ${path.relative(process.cwd(), path.join(OUT_DIR, 'schema.sql'))}`);
    console.log(`[snapshot] ${roles.length} built-in roles written to ${path.relative(process.cwd(), path.join(OUT_DIR, 'seed.sql'))}`);
  } finally {
    await connection.end();
  }
  process.exit(0);
})().catch((err) => {
  console.error('[snapshot] failed:', err.message);
  process.exit(1);
});
